/*
===========================================================================

openQ4 system check: the screen before the main menu that offers the
detected performance preset whenever the preset system's version differs
from the one this configuration last checked (PerformancePresetCheck.h,
docs/dev/ui/performance-presets.md "System check").

The retained interface presents guis/menu/presetcheck.rui (generated by
tools/ui/retained_preset_check.py); the stock interface, or a retained
document that cannot load, presents guis/presetcheck.gui. Both read the same
GUI state and answer with the same three verbs:

	presetCheckApply   apply the recommendation, restarting the renderer and
	                   sound when a setting moved, then open the main menu
	presetCheckKeep    keep every setting and record the version
	presetCheckLater   keep every setting and ask again at the next start

===========================================================================
*/

#include "Session_local.h"
#include "PerformancePresetCheck.h"
#include "SessionPresetCheck.h"

#include <string>

#ifndef ID_DEDICATED
namespace {

const char *const RETAINED_PRESET_CHECK_GUI = "guis/menu/presetcheck.rui";
const char *const STOCK_PRESET_CHECK_GUI = "guis/presetcheck.gui";

enum class PresetCheckStage { Idle, Showing, Applying };

struct PresetCheckScreen {
	idUserInterface *gui = NULL;
	bool retained = false;
	bool playIntro = true;      // the main menu plays its intro after a startup check
	PresetCheckStage stage = PresetCheckStage::Idle;
};
PresetCheckScreen presetCheck;

const char *Localized( const char *key ) {
	return common->GetLanguageDict()->GetString( key );
}

// The localized name of preset tier `tier` (#str_229977 lists all nine in
// PerformancePresets() order), or Custom for a selection outside them.
idStr PresetTierName( int tier ) {
	if ( tier < 0 || tier >= openq4::PerformancePresetCount ) {
		return Localized( "#str_232024" );
	}
	idStr names = Localized( "#str_229977" );
	int start = 0;
	for ( int index = 0; index <= tier; ++index ) {
		int end = names.Find( ';', start );
		if ( end < 0 ) end = names.Length();
		if ( index == tier ) {
			idStr name = names.Mid( start, end - start );
			name.StripLeading( ' ' );
			name.StripTrailing( ' ' );
			if ( name.Length() > 0 ) return name;
			break;
		}
		start = end + 1;
		if ( start > names.Length() ) break;
	}
	return openq4::PerformancePresets()[tier].name;
}

// A renderer's device name without the GL suffixes ("/PCIe/SSE2"), bounded so
// the readout keeps one line.
idStr AdapterName( const std::string &adapter ) {
	idStr name = adapter.c_str();
	const int slash = name.Find( '/' );
	if ( slash > 0 ) name = name.Left( slash );
	name.StripLeading( ' ' );
	name.StripTrailing( ' ' );
	name.RemoveColors();
	if ( name.Length() > 44 ) {
		name = name.Left( 41 );
		name.StripTrailing( ' ' );
		name += "...";
	}
	return name.Length() > 0 ? name : idStr( Localized( "#str_232016" ) );
}

idStr Gigabytes( int megabytes ) {
	const int gigabytes = ( megabytes + 512 ) / 1024;
	return va( Localized( "#str_232014" ), gigabytes > 0 ? gigabytes : 1 );
}

void Publish( idUserInterface *gui, const openq4::PerformancePresetCheck &check, bool retained ) {
	const char *body = check.matches ? "#str_232003" : check.neverChecked ? "#str_232002" : "#str_232001";
	gui->SetStateString( "check_body", Localized( body ) );
	gui->SetStateString( "check_primary", Localized( check.matches ? "#str_232027" : "#str_232011" ) );
	gui->SetStateString( "check_gpu", AdapterName( check.adapter ) );
	idStr vram;
	if ( check.videoRamMB > 0 ) {
		vram = Gigabytes( check.videoRamMB );
	} else {
		vram = Localized( check.gpuClass == RendererGpuClass::Integrated ? "#str_232015" : "#str_232016" );
	}
	gui->SetStateString( "check_vram", vram );
	gui->SetStateString( "check_ram", check.systemRamMB > 0 ? Gigabytes( check.systemRamMB ).c_str() : Localized( "#str_232016" ) );
	gui->SetStateString( "check_cpu", check.logicalCpus > 0 ? va( Localized( "#str_232017" ), check.logicalCpus ) : Localized( "#str_232016" ) );
	idStr display;
	if ( check.drawableWidth > 0 && check.drawableHeight > 0 ) {
		display = check.displayRefreshHz > 0 ?
			va( Localized( "#str_232018" ), check.drawableWidth, check.drawableHeight, check.displayRefreshHz ) :
			va( Localized( "#str_232019" ), check.drawableWidth, check.drawableHeight );
	} else {
		display = Localized( "#str_232016" );
	}
	gui->SetStateString( "check_display", display );
	gui->SetStateString( "check_current", PresetTierName( check.currentTier ) );
	gui->SetStateString( "check_recommended", PresetTierName( check.recommendedTier ) );
	gui->SetStateString( "check_tierLow", PresetTierName( 0 ) );
	gui->SetStateString( "check_tierHigh", PresetTierName( openq4::PerformancePresetCount - 1 ) );
	gui->SetStateString( "check_detail", check.maxFps > 0 ?
		va( Localized( "#str_232020" ), check.screenFraction, check.maxFps ) :
		va( Localized( "#str_232021" ), check.screenFraction ) );
	// Where the choice lives afterwards, in the menu's own words: SETTINGS >
	// DISPLAY in the retained interface, SETTINGS > SYSTEM in the stock one.
	gui->SetStateString( "check_footer", va( Localized( "#str_232023" ), Localized( "#str_200009" ),
		Localized( retained ? "#str_229900" : "#str_200085" ) ) );
	gui->SetStateInt( "check_currentTier", check.currentTier );
	gui->SetStateInt( "check_recommendedTier", check.recommendedTier );
	gui->SetStateBool( "check_matches", check.matches );
	gui->SetStateBool( "check_busy", false );
	gui->StateChanged( common->GetPresentationTime() );
}

// A check that something else took off the screen (a map started from the
// console, another menu) is over; its answers no longer apply.
void ForgetIfReplaced() {
	if ( presetCheck.stage == PresetCheckStage::Showing && sessLocal.guiActive != presetCheck.gui ) {
		common->Printf( "Performance preset check: replaced on screen; the check asks again at the next start\n" );
		presetCheck = PresetCheckScreen();
	}
}

void Finish() {
	const bool playIntro = presetCheck.playIntro;
	presetCheck = PresetCheckScreen();
	// Replaces the check; StartMenu deactivates it.
	sessLocal.StartMenu( playIntro );
}

void Answer( const char *answer ) {
	ForgetIfReplaced();
	if ( presetCheck.stage != PresetCheckStage::Showing || answer == NULL ) {
		return;
	}
	common->Printf( "PRESET_CHECK answer=%s ui=%s\n", answer, presetCheck.retained ? "retained" : "stock" );
	if ( !idStr::Icmp( answer, "apply" ) ) {
		bool changed = false;
		std::string error;
		if ( Common_ApplyPerformancePresetCheck( changed, error ) && changed ) {
			// The new preset reaches the device (textures, MSAA, scene targets)
			// and the sound backend before the main menu opens, as on a first
			// launch. The screen shows that it is working meanwhile.
			presetCheck.stage = PresetCheckStage::Applying;
			if ( presetCheck.gui != NULL ) {
				presetCheck.gui->SetStateBool( "check_busy", true );
				presetCheck.gui->StateChanged( common->GetPresentationTime() );
				presetCheck.gui->HandleNamedEvent( "presetCheckApplying" );
			}
			// Ahead of anything already queued (an autoexec, a script), so the
			// screen never waits behind it.
			cmdSystem->BufferCommandText( CMD_EXEC_INSERT, "vid_restart\ns_restart\nperformancePresetCheck finish\n" );
			return;
		}
		// Nothing moved, or the apply rolled back (the log says why; the
		// version stays unrecorded, so the next start asks again).
	} else if ( !idStr::Icmp( answer, "keep" ) ) {
		Common_RecordPerformancePresetCheck( "kept the current settings" );
	} else if ( !idStr::Icmp( answer, "later" ) ) {
		common->Printf( "Performance preset check: settings kept; the check asks again at the next start\n" );
	} else {
		return;
	}
	Finish();
}

// The stock screen's commands: "play <sound>" and the three answers, in any
// ;-separated order, as the stock menus send them.
const char *StockCommand( const char *menuCommand ) {
	idCmdArgs args( menuCommand, false );
	for ( int i = 0; i < args.Argc(); ) {
		const char *cmd = args.Argv( i++ );
		if ( !idStr::Icmp( cmd, "play" ) ) {
			if ( i < args.Argc() && sessLocal.menuSoundWorld != NULL ) {
				sessLocal.menuSoundWorld->PlayShaderDirectly( args.Argv( i++ ), 1 );
			}
		} else if ( !idStr::Icmp( cmd, "presetCheckApply" ) ) {
			Answer( "apply" );
		} else if ( !idStr::Icmp( cmd, "presetCheckKeep" ) ) {
			Answer( "keep" );
		} else if ( !idStr::Icmp( cmd, "presetCheckLater" ) ) {
			Answer( "later" );
		}
	}
	return "";
}

} // namespace
#endif

bool Session_StartPresetCheck( bool force ) {
#ifdef ID_DEDICATED
	(void)force;
	return false;
#else
	ForgetIfReplaced();
	if ( presetCheck.stage != PresetCheckStage::Idle ) {
		return true;
	}
	if ( sessLocal.guiMainMenu == NULL || sessLocal.mapSpawned || ( !force && !Common_PerformancePresetCheckDue() ) ) {
		return false;
	}
	openq4::PerformancePresetCheck check;
	std::string error;
	if ( !Common_DescribePerformancePresetCheck( check, error ) ) {
		common->Printf( "Performance preset check: skipped, detection unavailable (%s)\n", error.c_str() );
		return false;
	}
	idUserInterface *gui = NULL;
	bool retained = false;
	if ( cvarSystem->GetCVarBool( "ui_retained" ) ) {
		gui = sessLocal.FindRetainedGui( RETAINED_PRESET_CHECK_GUI, true, false );
		retained = gui != NULL;
	}
	if ( gui == NULL ) {
		gui = uiManager->FindGui( STOCK_PRESET_CHECK_GUI, true, false, true );
	}
	if ( gui == NULL ) {
		common->Warning( "Performance preset check: '%s' could not be loaded; the main menu opens instead", STOCK_PRESET_CHECK_GUI );
		return false;
	}
	common->Printf( "PRESET_CHECK show ui=%s stored='%s' version=%s current=%s recommended=%s differences=%d (%s)\n",
		retained ? "retained" : "stock", check.stored.c_str(), check.version.c_str(), check.current.c_str(),
		check.recommended.c_str(), check.differences, check.summary.c_str() );
	Publish( gui, check, retained );
	// A check opened from the console over the main menu returns to it as it
	// was; the startup check hands over to the menu's intro.
	presetCheck.playIntro = !force || sessLocal.guiActive == NULL;
	presetCheck.gui = gui;
	presetCheck.retained = retained;
	presetCheck.stage = PresetCheckStage::Showing;
	console->Close();
	sessLocal.SetPlayingSoundWorld( sessLocal.menuSoundWorld );
	sessLocal.SetGUI( gui, retained ? NULL : StockCommand );
	return true;
#endif
}

bool Session_PresetCheckOwns( const idUserInterface *gui ) {
#ifdef ID_DEDICATED
	(void)gui;
	return false;
#else
	return gui != NULL && presetCheck.retained && gui == presetCheck.gui;
#endif
}

void Session_PresetCheckRequest( idUserInterface *gui, const char *request ) {
#ifdef ID_DEDICATED
	(void)gui; (void)request;
#else
	if ( !Session_PresetCheckOwns( gui ) || gui != sessLocal.guiActive || request == NULL ) {
		return;
	}
	if ( !idStr::Icmp( request, "presetCheckApply" ) ) {
		Answer( "apply" );
	} else if ( !idStr::Icmp( request, "presetCheckKeep" ) ) {
		Answer( "keep" );
	} else if ( !idStr::Icmp( request, "presetCheckLater" ) ) {
		Answer( "later" );
	}
#endif
}

void Session_PresetCheck_f( const idCmdArgs &args ) {
	const char *verb = args.Argc() > 1 ? args.Argv( 1 ) : "status";
#ifndef ID_DEDICATED
	if ( !idStr::Icmp( verb, "open" ) ) {
		if ( !Session_StartPresetCheck( true ) ) {
			common->Printf( "performancePresetCheck: the check opens only from the front end, with a renderer and menus\n" );
		}
		return;
	}
	if ( !idStr::Icmp( verb, "apply" ) || !idStr::Icmp( verb, "keep" ) || !idStr::Icmp( verb, "later" ) ) {
		ForgetIfReplaced();
		if ( presetCheck.stage != PresetCheckStage::Showing ) {
			common->Printf( "performancePresetCheck: the check is not showing\n" );
			return;
		}
		Answer( verb );
		return;
	}
	if ( !idStr::Icmp( verb, "finish" ) ) {
		// The end of an apply: the renderer and sound restarted with the new preset.
		if ( presetCheck.stage == PresetCheckStage::Applying ) {
			Finish();
		}
		return;
	}
#endif
	if ( !idStr::Icmp( verb, "reset" ) ) {
		Common_ClearPerformancePresetCheck();
		common->Printf( "performancePresetCheck: the record is cleared; the check asks at the next start\n" );
		return;
	}
	if ( idStr::Icmp( verb, "status" ) ) {
		common->Printf( "usage: performancePresetCheck [status|open|apply|keep|later|reset]\n" );
		return;
	}
	common->Printf( "Preset system version %s (revision %d, %d machines in the fingerprint); recorded '%s'; due=%d\n",
		openq4::PerformancePresetSystemVersion().c_str(), openq4::PerformancePresetSystemRevision,
		openq4::PerformancePresetFingerprintMachines(), cvarSystem->GetCVarString( "com_performancePresetCheck" ),
		Common_PerformancePresetCheckDue() ? 1 : 0 );
	openq4::PerformancePresetCheck check;
	std::string error;
	if ( Common_DescribePerformancePresetCheck( check, error ) ) {
		common->Printf( "Current '%s', recommended '%s' (%d setting%s would change): %s\n", check.current.c_str(),
			check.recommended.c_str(), check.differences, check.differences == 1 ? "" : "s", check.summary.c_str() );
	} else {
		common->Printf( "Recommendation unavailable: %s\n", error.c_str() );
	}
}
