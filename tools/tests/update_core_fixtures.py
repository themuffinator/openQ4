#!/usr/bin/env python3
"""Write tools/tests/native/UpdateCoreFixtures.inc for the update core test.

The fixtures are committed so building the tests needs no third-party Python
package. Regenerate them (this needs `cryptography`) when the manifest schema
or the cases change:

    python tools/tests/update_core_fixtures.py

The signing key is derived from a fixed test seed. It is not, and must never
become, the release signing key.
"""

from __future__ import annotations

import hashlib
import io
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "tools" / "tests" / "native" / "UpdateCoreFixtures.inc"
TEST_SEED = hashlib.sha256(b"openQ4 update core test key - not a release key").digest()


def manifest_bytes(version: str = "0.15.0", **overrides) -> bytes:
    document = {
        "schema": 1,
        "product": "openQ4",
        "version": version,
        "tag": "v" + version,
        "packages": {
            "windows-x64": {
                "archive": f"openq4-{version}-windows-x64-update.zip",
                "size": 62371819,
                "sha256": "ab" * 32,
            },
            "linux-x64": {
                "archive": f"openq4-{version}-linux-x64-update.tar.xz",
                "size": 78994064,
                "sha256": "CD" * 32,
            },
        },
        "packs": [
            {"name": "pak0.pk4", "md5": "f9" * 16, "sha256": "fd" * 32, "size": 14283410, "bulk": False},
            {"name": "pak1.pk4", "md5": "0f" * 16, "sha256": "d8" * 32, "size": 96376779, "bulk": True},
        ],
    }
    document.update(overrides)
    return (json.dumps(document, indent=2, sort_keys=True) + "\n").encode("utf-8")


def zip_bytes(members: list[tuple[str, bytes, int]]) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, data, method in members:
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = method
            info.create_system = 3
            info.external_attr = (0o755 if name.endswith(".sh") else 0o644) << 16
            archive.writestr(info, data)
    return buffer.getvalue()


def corrupt_crc(data: bytes) -> bytes:
    # Flip one byte of the first member's payload: the local header is 30
    # bytes plus the name, and the member is stored.
    patched = bytearray(data)
    name_length = int.from_bytes(patched[26:28], "little")
    patched[30 + name_length] ^= 0xFF
    return bytes(patched)


def c_bytes(name: str, data: bytes) -> str:
    rows = []
    for start in range(0, len(data), 24):
        rows.append("\t" + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 24]) + ",")
    if not rows:
        rows.append("\t0x00,")
    return f"static const unsigned char {name}[] = {{\n" + "\n".join(rows) + f"\n}};\nstatic const size_t {name}_SIZE = {len(data)};\n"


def c_string(name: str, text: str) -> str:
    return f'static const char {name}[] = "{text}";\n'


def main() -> int:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    key = Ed25519PrivateKey.from_private_bytes(TEST_SEED)
    public = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    good = manifest_bytes()
    signature = key.sign(good).hex()
    other_key = Ed25519PrivateKey.from_private_bytes(hashlib.sha256(b"another key").digest())

    payload = bytes(range(256)) * 64
    good_zip = zip_bytes([
        ("README.txt", b"openQ4 update test\n", zipfile.ZIP_STORED),
        ("baseoq4/game-sp_x64.dll", payload, zipfile.ZIP_DEFLATED),
        ("launch.sh", b"#!/bin/sh\nexit 0\n", zipfile.ZIP_DEFLATED),
        ("empty.txt", b"", zipfile.ZIP_DEFLATED),
    ])
    traversal_zip = zip_bytes([("../escape.txt", b"no", zipfile.ZIP_STORED)])
    absolute_zip = zip_bytes([("/etc/escape.txt", b"no", zipfile.ZIP_STORED)])
    reserved_zip = zip_bytes([(".update/plan.txt", b"no", zipfile.ZIP_STORED)])
    bad_crc_zip = corrupt_crc(zip_bytes([("README.txt", b"openQ4 update test\n", zipfile.ZIP_STORED)]))

    parts = [
        "// Generated by tools/tests/update_core_fixtures.py; do not edit.\n",
        "// The key is a fixed test key, not the release signing key.\n\n",
        c_string("FIXTURE_PUBLIC_KEY", public.hex()),
        c_string("FIXTURE_SIGNATURE", signature),
        c_string("FIXTURE_OTHER_SIGNATURE", other_key.sign(good).hex()),
        c_bytes("FIXTURE_MANIFEST", good),
        c_bytes("FIXTURE_MANIFEST_TAMPERED", good.replace(b"62371819", b"62371818")),
        c_bytes("FIXTURE_MANIFEST_BAD_TAG", manifest_bytes(tag="v0.15.1")),
        c_bytes("FIXTURE_MANIFEST_BAD_ASSET", manifest_bytes(packages={
            "windows-x64": {"archive": "../openq4.zip", "size": 1, "sha256": "ab" * 32}})),
        c_bytes("FIXTURE_MANIFEST_BAD_PRODUCT", manifest_bytes(product="Quake4")),
        c_bytes("FIXTURE_MANIFEST_BAD_VERSION", manifest_bytes(version="0.15.0-rc.1")),
        c_bytes("FIXTURE_ZIP_GOOD", good_zip),
        c_bytes("FIXTURE_ZIP_TRAVERSAL", traversal_zip),
        c_bytes("FIXTURE_ZIP_ABSOLUTE", absolute_zip),
        c_bytes("FIXTURE_ZIP_RESERVED", reserved_zip),
        c_bytes("FIXTURE_ZIP_BAD_CRC", bad_crc_zip),
        c_string("FIXTURE_PAYLOAD_SHA256", hashlib.sha256(payload).hexdigest()),
    ]
    OUTPUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
