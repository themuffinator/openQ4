#!/usr/bin/env python3
"""Generate the Remastered HUD documents (visual specification 14.1-14.12).

Each document is the Remastered layout of a stock HUD GUI. The engine pairs
it with that GUI (src/ui/RetainedHud.cpp, idRemasteredHud): the document
receives the same state keys and named events the game sends the stock GUI,
and draws the atlas constructions on the section 14.4 layout - the 4:3 center
screen, side screens and bands, nine anchors, the 21:9 cap, HUD scale and the
safe inset. Classic (ui_hudLayout 0) keeps the stock GUI.

    python tools/ui/build_remastered_hud.py [--check]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import build_retained_screens as ui
from remastered_hud_base import (AND, NOT, S, HudDocument, anchor, beyond_minimal, gameplay_root, join_events, layout_state,
                                 op, sel, status_scale, u)
from remastered_hud_groups import (boss_bar, dev_readouts, hit_indicator, interactive_brackets, missile_chevron, notices,
                                   pickup_lines, powerups, transmission, weapon_strip)
from remastered_hud_lint import lint
from remastered_hud_mp import mp_document
from remastered_hud_status import air_gauge, full, status_bar
from remastered_hud_objectives import objectives_document
from remastered_hud_scoreboard import scoreboard_document
from remastered_hud_vehicle import airdef_document, ride_gauge, vehicle_document
from remastered_hud_awakening import (chaingun_turret_document, gev_document, mcc_document, ship_panel, speeder_document,
                                      turret_document)
from remastered_hud_medchange import medchange_document

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "content/baseoq4/pak0/guis/hud"
HEADER = "// Generated by tools/ui/build_remastered_hud.py; the Remastered HUD (ui-visual-design.md 14.4-14.12).\n"


def center_box(ident: str, children: list) -> dict:
    """The unscaled 4:3 canvas at the view centre: world-projected groups
    (interactive brackets) arrive in its coordinates."""
    return ui.group(ident, {"position": ui.keyword("absolute"), "left": ui.length(50, "%"), "top": ui.length(50, "%"),
                            "margin-left": ui.length(-480), "margin-top": ui.length(-360), "width": ui.length(960),
                            "height": ui.length(720), "display": ui.keyword("block")}, children)


def classic_air_document(*, strogg: bool) -> dict:
    doc = HudDocument("openq4.hud.air." + ("strogg" if strogg else "marine"))
    layout_state(doc)
    doc.number("player_health", 0)
    doc.boolean("oq4.hidden")
    doc.boolean("oq4.ride")
    gauge = air_gauge(doc, strogg, classic=True)
    doc.on("hideHud", {"op": "setState", "values": {"oq4.hidden": True}})
    doc.on("showHud", {"op": "setState", "values": {"oq4.hidden": False}})
    for event in ("enterFlatbed", "enterTram"):
        doc.on(event, {"op": "setState", "values": {"oq4.ride": True}})
    for event in ("exitFlatbed", "exitTram"):
        doc.on(event, {"op": "setState", "values": {"oq4.ride": False}})
    doc.on("hudJoin")
    doc.on("onInit")
    joins = join_events(doc, [("desktop::hidden", "hideHud"),
                             ("p_tram::visible", "enterTram") if strogg else ("p_flatbed::visible", "enterFlatbed")])
    # The stock 4:3 canvas, centered horizontally and attached to the bottom
    # in tall views. This essential instrument does not adopt Remastered scale.
    canvas = ui.group("air-classic-canvas", {"position": ui.keyword("absolute"),
        "left": ui.length(50, "%"), "top": ui.length(100, "%"),
        "margin-left": ui.length(-480), "margin-top": ui.length(-720),
        "width": ui.length(960), "height": ui.length(720)}, [gauge])
    # The stock interface's Remastered layout centres the stock status bar
    # (oq4_hudRemastered, idLegacyHudLayout): the gauge follows its health gauge.
    doc.boolean("oq4_hudRemastered")
    doc.bind("air-classic-canvas.status", "air-classic-canvas", "margin-left",
             op("+", -480, sel(S("oq4_hudRemastered"), u(85.5 if strogg else 88), 0)))
    return doc.build(full("air-classic-root", [canvas]), {"canvas": {"height": 720, "minWidth": 960},
        "extensions": {"openq4": {"joinEvents": joins, "reference": "ui-visual-design.md 14.3"}}})


def on_foot_document(*, strogg: bool, awakening: bool) -> dict:
    """The on-foot HUD (hud.gui, hud_strogg.gui and The Awakening's
    q4xhud*.gui): status bar, weapon strip, pickups, transmission, boss bar,
    notices, brackets and damage direction. Multiplayer draws its gauges
    from the same Marine document (state `mp`)."""
    family = "strogg" if strogg else "marine"
    doc = HudDocument(f"openq4.hud.remastered.{family}{'.awakening' if awakening else ''}")
    layout_state(doc)
    gauges = status_bar(doc, strogg=strogg, mp_variants=not strogg)
    ride = ride_gauge(doc, strogg=strogg)
    strip = weapon_strip(doc, strogg=strogg, awakening=awakening)
    pickups = pickup_lines(doc, strogg=strogg)
    radio = transmission(doc, strogg=strogg, emblem="squad_falcon" if awakening else "radio_rhino")
    hit = hit_indicator(doc)
    brackets = interactive_brackets(doc)
    boss = boss_bar(doc)
    exit_notice, saved, missile_text = notices(doc)
    missile = missile_chevron(doc)
    speed, comments = dev_readouts(doc)
    # The Awakening's m03 script also sends the ship panel's markers, damage and
    # warnings to the player's HUD, which the expansion's HUD cannot show.
    ship = [ship_panel(doc, always=False, cone=False)] if awakening else []
    # Multiplayer draws its gauges from the Marine document (state mp).
    trailing_bottom = [] if strogg or awakening else [powerups(doc)]

    doc.on("hideHud", {"op": "setState", "values": {"oq4.hidden": True, "oq4.strip": False}})
    doc.on("showHud", {"op": "setState", "values": {"oq4.hidden": False}})
    doc.on("hudJoin", *doc.joins)
    doc.on("onInit", *doc.joins)

    # Minimal (ui_hudLayout 2) keeps the gauges, the ride's gauge, the
    # brackets, the save notice and the developer readouts a player turned on.
    root = gameplay_root(doc, "hud-root", [
        center_box("hud-world", [brackets]),
        anchor(doc, "bc", gauges + [ride, beyond_minimal(doc, "bc-full", [pickups, strip])], scale=status_scale(S("mp"))),
        anchor(doc, "tr", [beyond_minimal(doc, "tr-full", [radio]), speed, *ship]),
        anchor(doc, "tc", [beyond_minimal(doc, "tc-full", [boss, missile_text, exit_notice]), saved]),
        anchor(doc, "cc", [beyond_minimal(doc, "cc-full", [hit, missile])]),
        anchor(doc, "tl", [comments]),
        anchor(doc, "br", [beyond_minimal(doc, "br-full", trailing_bottom)] if trailing_bottom else []),
    ])
    # The stock windows that hold an event's lasting effect (hud.gui and its family).
    ride = ("p_tram::visible", "enterTram") if strogg else ("p_flatbed::visible", "enterFlatbed")
    # The dropship panel's damage and markers, which openQ4's definition of the
    # expansion's HUD keeps in its windows (tools/ui/build_awakening_legacy_hud.py);
    # the panel's own visibility comes last, since each of those also shows it.
    ship_joins = [*[(f"ship_core_{n + 1:02d}::visible", f"ship_health_{n:02d}_on") for n in range(1, 6)],
                  *[(f"ship_target_{n:02d}::visible", f"ship_target_{n:02d}_on") for n in range(1, 6)],
                  ("shipstatus::visible", "aa_showShipStatusOn"),
                  ("!shipstatus::visible", "aa_showShipStatusOff")] if awakening else []
    joins = join_events(doc, [("desktop::hidden", "hideHud"), ("p_radio::visible", "radioChatterUp"),
                              ("BossBar::visible", "showBossBar"), ("p_boss_shield_bar_left::visible", "showBossShieldBar"),
                              ("brackets::visible", "showBrackets"), ("missile_indicator::visible", "missileThreatUp"), ride, *ship_joins])
    return doc.build(root, {"canvas": {"height": 720, "minWidth": 960},
                            "extensions": {"openq4": {"reference": "ui-visual-design.md 14.3-14.12",
                                                      "stock": "guis/hud_strogg.gui" if strogg else "guis/hud.gui",
                                                      "awakening": awakening, "joinEvents": joins}}})


DOCUMENTS = {
    "air_marine.q4ui": lambda: classic_air_document(strogg=False),
    "air_strogg.q4ui": lambda: classic_air_document(strogg=True),
    "remastered_marine.q4ui": lambda: on_foot_document(strogg=False, awakening=False),
    "remastered_strogg.q4ui": lambda: on_foot_document(strogg=True, awakening=False),
    "remastered_marine_awakening.q4ui": lambda: on_foot_document(strogg=False, awakening=True),
    "remastered_strogg_awakening.q4ui": lambda: on_foot_document(strogg=True, awakening=True),
    "remastered_mp.q4ui": mp_document,
    "remastered_vehicle.q4ui": vehicle_document,
    "remastered_airdef.q4ui": airdef_document,
    "remastered_turret.q4ui": turret_document,
    "remastered_mcc.q4ui": mcc_document,
    "remastered_chaingun_turret.q4ui": chaingun_turret_document,
    "remastered_speeder.q4ui": speeder_document,
    "remastered_gev.q4ui": gev_document,
    "remastered_medchange.q4ui": medchange_document,
    "remastered_objectives.q4ui": lambda: objectives_document(strogg=False),
    "remastered_objectives_strogg.q4ui": lambda: objectives_document(strogg=True),
    "remastered_scoreboard.q4ui": scoreboard_document,
}


def render(build) -> str:
    document = build()
    problems = lint(document)
    if problems:
        raise SystemExit("Remastered HUD document problems:\n  " + "\n  ".join(problems[:80]))
    # Compact JSON: the vector paths dominate and indentation would triple it.
    return HEADER + json.dumps(document, separators=(",", ":"), ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when a generated document is stale")
    parser.add_argument("--only", action="append", help="build only these documents")
    args = parser.parse_args()
    stale = []
    for name, build in DOCUMENTS.items():
        if args.only and name not in args.only:
            continue
        path = OUT / name
        text = render(build)
        if args.check:
            current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
            if current != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"{path.relative_to(ROOT)}: {len(text) // 1024} KiB")
    if stale:
        print("stale:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
