#!/usr/bin/env python3
"""Generate the stock interface's HUD for The Awakening (guis/q4xhud.gui).

The expansion's on-foot HUD is the stock guis/hud.gui of its day with four
additions: weapon strip slots 11 and 12 (the campaign carries 13 weapons), the
dropship status panel of m03, a death fade and a failed-objective title. Its
script knows nothing of the Remastered layout, so the engine reads this
definition in its place (idLegacyHudLayout::DefinitionFor) while q4xbase is
active and no mod ships its own copy.

The definition is openQ4's guis/hud.gui with those additions, so every layout,
setting and fix of the stock interface's HUD (docs/dev/ui/legacy-hud-layout.md)
reaches The Awakening, and an edit to hud.gui leaves this file stale until it
is regenerated. The panel's art is the expansion's own, which only q4xbase
ships; nothing reads this file without it.

    python tools/ui/build_awakening_legacy_hud.py [--check]
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAK0 = ROOT / "content/baseoq4/pak0"
SOURCE = PAK0 / "guis/hud.gui"
OUT = PAK0 / "guis/openq4/awakening/q4xhud.gui"
ART = "gfx/guis/vehicle/airassault/"

HEADER = """// Generated by tools/ui/build_awakening_legacy_hud.py from guis/hud.gui; do not edit.
// The stock interface's HUD for The Awakening: the engine reads this definition
// in place of the expansion's guis/q4xhud.gui (docs/dev/ui/legacy-hud-layout.md).

"""

# The ship panel (findings: the expansion's turret HUD answers these events, its
# on-foot HUD has the windows but no handlers, and m03 sends them to both).
# ship_health_01..05: left wing, right wing, nose, tail, mid body.
DAMAGE = 5
# ship_target_01..05: the objective markers (16 u, local to the panel).
TARGETS = [(48, 75), (56, 71), (47, 58), (46, 43), (57, 29)]
# warning_<dir>: the darts on the rim (24 u, local to the panel).
WARNINGS = [("N", 53, -2), ("NE", 95, 13), ("E", 102, 51), ("SE", 93, 91), ("S", 52, 110), ("SW", 11, 92), ("W", 1, 50),
            ("NW", 9, 11)]


def events() -> str:
    out = ["""
//-----------------------
// The Awakening
//-----------------------

	// The dropship panel (m03). The expansion's HUD showed it between these two
	// events only; its markers, damage and warnings reached the gun's HUD alone.
	onNamedEvent aa_showShipStatusOn {
		set "shipstatus::visible" "1" ;
	}

	onNamedEvent aa_showShipStatusOff {
		set "shipstatus::visible" "0" ;
	}
"""]
    for index in range(1, DAMAGE + 1):
        out.append(f"""
	onNamedEvent ship_health_{index:02d}_on {{
		set "ship_core_{index + 1:02d}::visible" "1" ;
		set "shipstatus::visible" "1" ;
	}}

	onNamedEvent ship_health_{index:02d}_off {{
		set "ship_core_{index + 1:02d}::visible" "0" ;
		set "shipstatus::visible" "1" ;
	}}
""")
    for index in range(1, len(TARGETS) + 1):
        out.append(f"""
	onNamedEvent ship_target_{index:02d}_on {{
		set "ship_target_{index:02d}::visible" "1" ;
		set "shipstatus::visible" "1" ;
	}}

	onNamedEvent ship_target_{index:02d}_off {{
		set "ship_target_{index:02d}::visible" "0" ;
	}}
""")
    for name, _, _ in WARNINGS:
        out.append(f"""
	onNamedEvent warning_{name} {{
		set "shipstatus::visible" "1" ;
		resettime "warning_anim_{name}" "0" ;
	}}
""")
    out.append("""
	onNamedEvent objectiveFailed {
		namedEvent "closeObjective";
		set "p_failedobjective::visible" "1";
	}

	onNamedEvent deathFadeIn {
		resettime "anim_deathFadeIn" "0";
	}
""")
    return "".join(out)


# Under every other window, as the expansion has them. The fade covers the
# whole view, not the 4:3 canvas alone (as hud.gui's own fade does).
FIRST = """
//-----------------------
// The Awakening: death fade and failed objective
//-----------------------

	windowDef deathFade
	{
		rect	0 - "gui::virtual_screen_x_expand",0 - "gui::virtual_screen_y_expand",640 + 2 * "gui::virtual_screen_x_expand",480 + 2 * "gui::virtual_screen_y_expand"
		backcolor	0,0,0,0
		visible	1
	}

	windowDef p_failedobjective
	{
		rect	0,200,640,80
		visible	0
		windowDef failedtitle
		{
			rect	0,40,640,40
			text	"gui::objectivetitle"
			textscale	0.5
			textalign	1
			font	"fonts/chain"
			forecolor	1,1,1,1
		}
	}

"""


def image(name: str, rect: str, art: str, *, visible: str = "0", colour: str = "1,1,1,1", extra: str = "") -> str:
    return f"""		windowDef {name}
		{{
			rect	{rect}
			visible	{visible}
			background	"{ART}{art}"
			matcolor	{colour}
{extra}		}}
"""


def tail() -> str:
    out = ["""
//-----------------------
// The Awakening: the dropship panel (m03)
//-----------------------

	windowDef anim_deathFadeIn
	{
		rect	0,0,1,1
		visible	1
		notime	1

		onTime 0 {
			transition "deathFade::backcolor" "0,0,0,0" "0,0,0,1" "3000" ;
		}
	}

	// The top trailing corner, under the transmission display. Remastered
	// (ui-visual-design.md 14.12) lets the view through the disc and, on foot,
	// leaves out the gun's view cone.
	windowDef shipstatus
	{
		rect	512,32,128,128
		screenalignx	right
		screenaligny	top
		visible	0
""",
           image("ship_base_01", "0,0,128,128", "hud_base_01", visible="1", colour='1,1,1,1 - 0.15 * "gui::oq4_hudRemastered"'),
           image("ship_base_02", "0,0,128,128", "hud_base_02", visible="1", colour="1,1,1,0.501"),
           image("ship_core_01", "27,0,75,128", "hud_ship_01", visible="1")]
    for index in range(1, DAMAGE + 1):
        out.append(image(f"ship_core_{index + 1:02d}", "27,0,75,128", f"hud_ship_{index + 1:02d}"))
    for index, (x, y) in enumerate(TARGETS, start=1):
        out.append(image(f"ship_target_{index:02d}", f"{x},{y},16,16", "hud_target_01"))
    for name, x, y in WARNINGS:
        out.append(image(f"ship_warning_{name}", f"{x},{y},24,24", f"hud_warning_{name}"))
    for name, _, _ in WARNINGS:
        out.append(f"""		windowDef warning_anim_{name}
		{{
			rect	-510,0,1,1
			visible	1
			notime	1

			onTime 0 {{
				set "ship_warning_{name}::visible" "1" ;
				transition "ship_warning_{name}::matcolor" "1,1,1,1" "0,0,0,0" "3000" ;
			}}
		}}
""")
    out.append(image("viewtracking", "4,4,120,120", "hud_base_03", visible='1 - "gui::oq4_hudRemastered"',
                     extra='\t\t\trotate\t"gui::playerYaw"\n'))
    out.append("\t}\n\n")
    return "".join(out)


def block_end(text: str, start: int) -> int:
    """The index after the brace that closes the first block opening at or after start."""
    depth = 0
    index = start
    while index < len(text):
        ch = text[index]
        if ch == '"':
            index = text.index('"', index + 1)
        elif text.startswith("//", index):
            index = text.index("\n", index)
            continue
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    raise ValueError("unbalanced block")


def line_end(text: str, index: int) -> int:
    return text.index("\n", index) + 1


def once(text: str, needle: str) -> int:
    if text.count(needle) != 1:
        raise ValueError(f"guis/hud.gui holds {text.count(needle)} of {needle!r}; the generator needs exactly one")
    return text.index(needle)


def slot(text: str, number: int) -> str:
    return re.sub(r"\b10\b", str(number), text.replace("weapon10", f"weapon{number}"))


def generate(source: str) -> str:
    text = source.replace("\r\n", "\n")
    for name in ("deathFade", "p_failedobjective", "shipstatus", "ws_weapon11"):
        if re.search(rf"windowDef\s+{name}\b", text):
            raise ValueError(f"guis/hud.gui already defines {name}")

    # The named events, after onInit.
    at = line_end(text, block_end(text, once(text, "\tonInit {")))
    text = text[:at] + events() + text[at:]

    # The fade and the failed objective, before the first window (and its banner).
    at = min(match.start() for match in re.finditer(r"^\twindowDef ", text, re.MULTILINE))
    while True:
        previous = text.rfind("\n", 0, at - 1) + 1
        line = text[previous:at].strip()
        if line and not line.startswith("//"):
            break
        at = previous
    text = text[:at] + FIRST + text[at:]

    # weaponChange: slots 11 and 12 answer as slot 10 does.
    start = once(text, '\t\t\tif ( "gui::weapon10" ) {')
    end = block_end(text, start)
    if not text[end:].lstrip(" \t").startswith("else"):
        raise ValueError("slot 10's weaponChange block has no else branch")
    end = line_end(text, block_end(text, end))
    block = text[start:end]
    text = text[:end] + "".join("\n" + slot(block, number) for number in (11, 12)) + text[end:]

    # The strip's windows.
    start = once(text, "\t\twindowDef ws_weapon10\n")
    end = line_end(text, block_end(text, start))
    block = text[start:end]
    text = text[:end] + "".join(slot(block, number) for number in (11, 12)) + text[end:]

    # The panel and the fade's timeline, last (over the HUD, as the expansion draws them).
    at = text.rstrip().rfind("}")
    if text[at:].strip() != "}":
        raise ValueError("guis/hud.gui does not end with its desktop's closing brace")
    text = text[:at].rstrip("\n") + "\n" + tail() + "}\n"
    if text.count("{") != text.count("}"):
        raise ValueError("generated definition has unbalanced braces")
    return HEADER + text


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the generated definition is stale")
    args = parser.parse_args()
    generated = generate(SOURCE.read_text(encoding="latin-1"))
    if args.check:
        current = OUT.read_text(encoding="latin-1").replace("\r\n", "\n") if OUT.is_file() else None
        if current != generated:
            raise SystemExit(f"{OUT.relative_to(ROOT).as_posix()} is stale: run tools/ui/build_awakening_legacy_hud.py")
        print("build_awakening_legacy_hud: current")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generated, encoding="latin-1", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
