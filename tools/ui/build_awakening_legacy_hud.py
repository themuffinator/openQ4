def replace_once(text: str, old: str, new: str) -> str:
    once(text, old)
    return text.replace(old, new)


def generate_speeder(source: str) -> str:
    """The speeder bike. The expansion's HUD is the stock vehicle HUD with the
    gauges' warnings removed, the entry lines and exit prompt broken, the hover
    tank's weapon panels (the bike lists its machinegun first) and the race
    display and boost added. The vehicle HUD restores the first three."""
    text = vehicle_source(source, "oq4_race", "boosting", "boost_msg", "speedertimer")
    # The bike's weapons: 0 the machinegun, 1 the cannon, which recharges.
    text = set_visible(text, "p_mgun", '"gui::vehicle_weapon" == 0')
    text = set_visible(text, "p_cannon", '"gui::vehicle_weapon" == 1')
    text = set_visible(text, "p_weapcharge", '"gui::vehicle_weapon" == 1')
    text = set_visible(text, "p_rockets", "0")
    text = set_visible(text, "p_mgun_walker", "0")
    start = once(text, "\tonNamedEvent showWeapMsg {")
    end = block_end(text, start)
    lines = text[start:end]
    first, second = 'if ( "gui::vehicle_weapon" == 0 ) {', 'else if ( "gui::vehicle_weapon" == 1 ) {'
    once(lines, first)
    once(lines, second)
    lines = lines.replace(first, 'if ( "gui::vehicle_weapon" == 1 ) {').replace(second, 'else if ( "gui::vehicle_weapon" == 0 ) {')
    text = text[:start] + lines + text[end:]

    # The HUD prompt: the boost before Exit, on the same plate.
    start = window_start(text, "oq4_prompt")
    end = block_end(text, start)
    prompt = text[start:end]
    shown = re.search(r'^\t\tvisible\t"gui::oq4_hudRemastered" \* \((.*)\)$', prompt, re.MULTILINE)
    if shown is None:
        raise ValueError("the HUD prompt no longer shows by the Remastered layout and its lines")
    prompt = prompt[:shown.end(1)] + ' + ("gui::oq4_boost" < 2)' + prompt[shown.end(1):]
    prompt = replace_once(prompt, '\t\tdefinefloat\t"chip"\t"oq4_prompt_key::textwidth"\n',
                          '\t\tdefinefloat\t"chip"\t"oq4_prompt_key::textwidth"\n\t\tdefinefloat\t"boost"\t' + BOOST_WIDTH + "\n")
    prompt = replace_once(prompt, '\t\tdefinefloat\t"width"\t', '\t\tdefinefloat\t"width"\t"oq4_prompt::boost" + ')
    if prompt.count('"oq4_prompt::left" + ') != 4:
        raise ValueError("the HUD prompt no longer places four items from its leading edge")
    prompt = prompt.replace('"oq4_prompt::left" + ', '"oq4_prompt::left" + "oq4_prompt::boost" + ')
    at = prompt.rstrip().rfind("}")
    prompt = prompt[:at] + BOOST_ITEMS + "\t}"
    text = text[:start] + prompt + text[end:]

    text = add_events(text, race_events())
    # Under the boss bar and the notices, as the Remastered display is.
    race, boost = race_windows()
    text = add_windows_before(text, "p_exit_level", race)
    text = add_windows(text, boost)
    return finish(text, vehicle_header("guis/vehicles/speederplayerhud.gui", "speeder bike"))


def outputs() -> dict:
    on_foot = SOURCE.read_text(encoding="latin-1")
    vehicle = VEHICLE_SOURCE.read_text(encoding="latin-1")
    return {
        OUT: generate(on_foot),
        OUT_DIR / "turretplayerhud.gui": generate_turret(vehicle),
        OUT_DIR / "cannonplayerhud.gui": generate_mcc(vehicle),
        OUT_DIR / "speederplayerhud.gui": generate_speeder(vehicle),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when a generated definition is stale")
    args = parser.parse_args()
    stale = []
    for path, generated in outputs().items():
        if args.check:
            current = path.read_text(encoding="latin-1").replace("\r\n", "\n") if path.is_file() else None
            if current != generated:
                stale.append(path.relative_to(ROOT).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(generated, encoding="latin-1", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        raise SystemExit(f"{', '.join(stale)} stale: run tools/ui/build_awakening_legacy_hud.py")
    if args.check:
        print("build_awakening_legacy_hud: current")


if __name__ == "__main__":
    main()
