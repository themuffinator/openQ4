def block_end(text: str, start: int) -> int:
    """The index after the brace that closes the first block opening at or after start."""
    depth = 0
    index = start
    while index < len(text):
        ch = text[index]
        if ch == '"':
            index = text.index('"', index + 1)
        elif text.startswith("//", index):
            index = text.index("\n", index)
            continue
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    raise ValueError("unbalanced block")


def line_end(text: str, index: int) -> int:
    return text.index("\n", index) + 1


def once(text: str, needle: str) -> int:
    if text.count(needle) != 1:
        raise ValueError(f"the source holds {text.count(needle)} of {needle!r}; the generator needs exactly one")
    return text.index(needle)


def slot(text: str, number: int) -> str:
    return re.sub(r"\b10\b", str(number), text.replace("weapon10", f"weapon{number}"))


def generate(source: str) -> str:
    text = source.replace("\r\n", "\n")
    for name in ("deathFade", "p_failedobjective", "shipstatus", "ws_weapon11"):
        if re.search(rf"windowDef\s+{name}\b", text):
            raise ValueError(f"guis/hud.gui already defines {name}")

    # The named events, after onInit.
    at = line_end(text, block_end(text, once(text, "\tonInit {")))
    text = text[:at] + events() + text[at:]

    # The fade and the failed objective, before the first window (and its banner).
    at = min(match.start() for match in re.finditer(r"^\twindowDef ", text, re.MULTILINE))
    while True:
        previous = text.rfind("\n", 0, at - 1) + 1
        line = text[previous:at].strip()
        if line and not line.startswith("//"):
            break
        at = previous
    text = text[:at] + FIRST + text[at:]

    # weaponChange: slots 11 and 12 answer as slot 10 does.
    start = once(text, '\t\t\tif ( "gui::weapon10" ) {')
    end = block_end(text, start)
    if not text[end:].lstrip(" \t").startswith("else"):
        raise ValueError("slot 10's weaponChange block has no else branch")
    end = line_end(text, block_end(text, end))
    block = text[start:end]
    text = text[:end] + "".join("\n" + slot(block, number) for number in (11, 12)) + text[end:]

    # The strip's windows.
    start = once(text, "\t\twindowDef ws_weapon10\n")
    end = line_end(text, block_end(text, start))
    block = text[start:end]
    text = text[:end] + "".join(slot(block, number) for number in (11, 12)) + text[end:]

    # The panel and the fade's timeline, last (over the HUD, as the expansion draws them).
    at = text.rstrip().rfind("}")
    if text[at:].strip() != "}":
        raise ValueError("guis/hud.gui does not end with its desktop's closing brace")
    text = text[:at].rstrip("\n") + "\n" + tail() + "}\n"
    if text.count("{") != text.count("}"):
        raise ValueError("generated definition has unbalanced braces")
    return HEADER + text


