def window_start(text: str, name: str) -> int:
    return once(text, f"\twindowDef {name}\n\t{{\n")


def set_visible(text: str, name: str, expression: str) -> str:
    """Replace a top-level window's own visible line (before its first child)."""
    start = window_start(text, name)
    end = block_end(text, start)
    child = text.find("\t\twindowDef ", start, end)
    match = re.compile(r"^\t\tvisible\t.*$", re.MULTILINE).search(text, start, child if child >= 0 else end)
    if match is None:
        raise ValueError(f"{name} has no visible line of its own")
    return text[:match.start()] + f"\t\tvisible\t{expression}" + text[match.end():]


def add_windows_before(text: str, name: str, block: str) -> str:
    at = window_start(text, name)
    return text[:at] + block.lstrip("\n") + text[at:]


def add_events(text: str, block: str) -> str:
    at = line_end(text, block_end(text, once(text, "\tonInit {")))
    return text[:at] + block + text[at:]


def add_windows(text: str, block: str) -> str:
    at = text.rstrip().rfind("}")
    if text[at:].strip() != "}":
        raise ValueError("guis/vehicles/hud.gui does not end with its desktop's closing brace")
    return text[:at].rstrip("\n") + "\n" + block + "}\n"


def finish(text: str, header: str) -> str:
    if text.count("{") != text.count("}"):
        raise ValueError("generated definition has unbalanced braces")
    return header + text


def vehicle_source(source: str, *added: str) -> str:
    text = source.replace("\r\n", "\n")
    for name in added:
        if re.search(rf"windowDef\s+{name}\b", text):
            raise ValueError(f"guis/vehicles/hud.gui already defines {name}")
    return text


