#!/usr/bin/env python3
"""Generate an arm64 Android NDK Meson cross file without host SDK leakage."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import platform


def meson_string(value: str) -> str:
    if any(c in value for c in "\r\n\0"):
        raise ValueError("Cross-file values cannot contain newlines or NULs")
    return "'" + value.replace("\\", "/").replace("'", "\\'") + "'"


def generate(ndk: Path, api: int, host: str | None = None) -> str:
    if api < 24:
        raise ValueError("openQ4 requires Android API 24 or later")
    ndk = ndk.resolve()
    host = host or {"Windows": "windows-x86_64", "Linux": "linux-x86_64", "Darwin": "darwin-x86_64"}.get(platform.system())
    if host is None:
        raise ValueError("Unsupported NDK build host")
    toolchain = ndk / "toolchains/llvm/prebuilt" / host
    suffix = ".exe" if host.startswith("windows") else ""
    tools = {name: toolchain / "bin" / (binary + suffix) for name, binary in (
        ("c", "clang"), ("cpp", "clang++"), ("ar", "llvm-ar"), ("strip", "llvm-strip"),
    )}
    for path in tools.values():
        if not path.is_file():
            raise ValueError(f"Missing NDK tool: {path}")
    if not (toolchain / "sysroot/usr/lib/aarch64-linux-android" / str(api)).is_dir():
        raise ValueError(f"NDK does not contain the requested arm64 API {api}")
    lines = ["# Generated by tools/build/android_cross.py; Android arm64-v8a.", "[binaries]"]
    for name, path in tools.items():
        command = [meson_string(path.as_posix())]
        if name in ("c", "cpp"):
            command.append(meson_string(f"--target=aarch64-linux-android{api}"))
        lines.append(f"{name} = [{', '.join(command)}]")
    lines += [
        "", "[host_machine]", "system = 'android'", "cpu_family = 'aarch64'",
        "cpu = 'aarch64'", "endian = 'little'", "", "[properties]",
        "needs_exe_wrapper = true", f"sys_root = {meson_string(str(toolchain / 'sysroot'))}",
        f"android_ndk = {meson_string(str(ndk))}", f"android_api = {api}",
        "", "[built-in options]", "b_staticpic = true",
        "c_link_args = ['-Wl,-z,max-page-size=16384']",
        "cpp_link_args = ['-Wl,-z,max-page-size=16384']",
        # Engine/game/renderer DSOs must share one C++ runtime.
        "cpp_args = ['-stdlib=libc++']", "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ndk", type=Path, default=os.environ.get("ANDROID_NDK_HOME") or os.environ.get("ANDROID_NDK_ROOT"))
    parser.add_argument("--api", type=int, default=24)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    if args.ndk is None:
        parser.error("Pass --ndk or set ANDROID_NDK_HOME")
    try:
        contents = generate(args.ndk, args.api)
    except ValueError as exc:
        parser.error(str(exc))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(contents, encoding="utf-8")
    print(args.out.resolve())


if __name__ == "__main__":
    main()
